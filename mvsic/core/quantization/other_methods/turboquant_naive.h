// TurboQuant: two-stage vector quantization for near-optimal MSE and unbiased inner product
// (TurboQuant: Online Vector Quantization with Near-optimal Distortion Rate,
// arxiv.org/abs/2504.19874). Stage 1 (MSE): random rotation (e.g. FHT) + per-coordinate scalar
// quantization (scale/offset). Stage 2 (inner product): 1-bit QJL on residual r = x_rot -
// decode(base) for unbiased <q,x> estimate. Inner product: <q,x> ≈ base_ip + (sqrt(pi/2)/m) *
// sum_k sign(<g_k,r>) * <q,g_k>, with random g_k.
// Stage 1 uses Lloyd-Max quantization for N(0,1) (optimal MSE, uncorrelated residual for QJL).

