#!/usr/bin/env python3
"""Generate bench_search_all_inst.h and the 48 per-cell instantiation .cc
files under bench_search_all_inst/.

Run from anywhere:
    python3 mvsic/mvivf/gen_bench_search_all_inst.py

The generator is the source of truth; commit its output. To add a new
quantizer or variant, edit METRICS / VARIANTS / QUANTS below and rerun.
The dispatch logic in bench_search_all.cpp must be updated separately.
"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
INST_DIR = os.path.join(ROOT, "bench_search_all_inst")
HEADER_PATH = os.path.join(ROOT, "bench_search_all_inst.h")

# (tag, ChPoint type, metric value as C++ literal)
METRICS = [
    ("ip", "ChamferIP_Point", "false"),
    ("l2", "ChamferL2_Point", "true"),
]

# (tag, family template name)
VARIANTS = [
    ("regular", "IndexMVIVF"),
    ("flat",    "IndexMVIVFFlat"),
    ("spill",   "IndexMVIVFSpill"),
]

# (tag, model template — {m} substitutes the metric literal)
QUANTS = [
    ("none",  "NoQuantizer<{m}>"),
    ("pq",    "pq_mv::Model<{m}>"),
    ("fs",    "fastscan_mv::Model<{m}>"),
    ("rq",    "rabitq_mv::Model<{m}>"),
    ("tq",    "turboquant_mv::Model<{m}>"),
    ("spqtq", "pqtq_mv::Model<{m}>"),
    ("1btq",  "turboquant_1bit_mv::Model<{m}>"),
    ("1btqa", "turboquant_1bit_asym_mv::Model<{m}>"),
    ("8btq",  "turboquant_8bit_mv::Model<{m}>"),
]

CC_TEMPLATE = """\
// GENERATED by gen_bench_search_all_inst.py. Do not edit.
#include "mvsic/mvivf/bench_search_all_impl.h"

namespace mvsic {{
template void run_one<{ChPoint}, {m}, {Fam}<{m}, false, {Model}>>(
    RunOneCtx<{ChPoint}>&);
template void run_one<{ChPoint}, {m}, {Fam}<{m}, true,  {Model}>>(
    RunOneCtx<{ChPoint}>&);
}}  // namespace mvsic
"""

HEADER_PRELUDE = """\
#pragma once
// GENERATED by gen_bench_search_all_inst.py. Do not edit.
//
// Declares run_one<ChPoint, metric, IndexT> and provides extern template
// declarations for every (metric, variant, quantizer, compress) cell so the
// dispatch TU does not pay to instantiate them. The definitions live in
// bench_search_all_impl.h and are explicitly instantiated once per cell
// under bench_search_all_inst/.

#include <cstddef>
#include <string>
#include <vector>

#include "mvsic/core/bench_utils.h"
#include "mvsic/core/index_params.h"
#include "mvsic/core/quantization/fastscan_mv.h"
#include "mvsic/core/quantization/pq_mv.h"
#include "mvsic/core/quantization/pqtq_mv.h"
#include "mvsic/core/quantization/rabitq_mv.h"
#include "mvsic/core/quantization/turboquant_1bit_mv.h"
#include "mvsic/core/quantization/turboquant_1bit_asym_mv.h"
#include "mvsic/core/quantization/turboquant_8bit_mv.h"
#include "mvsic/core/quantization/turboquant_mv.h"
#include "mvsic/core/types/chamfer_ip_point.h"
#include "mvsic/core/types/chamfer_l2_point.h"
#include "mvsic/core/types/point_cloud_set.h"
#include "mvsic/mvivf/mvivf.h"
#include "mvsic/mvivf/mvivf_flat.h"
#include "mvsic/mvivf/mvivf_spill.h"

namespace mvsic {

enum class MVIVFVariant { Regular, Flat, Spill };

template <typename ChPoint>
struct RunOneCtx {
  PointCloudSet<ChPoint>* points;
  IndexParams ip;
  SearchParams sp_base;
  bench::DatasetPaths ds;
  bench::IOArgs io;
  MVIVFVariant variant;
  std::size_t k;
  std::size_t num_rerank;
  std::vector<std::size_t> nprobes_list;
};

template <typename ChPoint, bool metric, class IndexT>
void run_one(RunOneCtx<ChPoint>& ctx);

"""

HEADER_EPILOGUE = """\

}  // namespace mvsic
"""


def main():
    os.makedirs(INST_DIR, exist_ok=True)

    # 48 per-cell .cc files (each instantiates compress=false and compress=true).
    written_cc = []
    for metric_tag, ChPoint, m in METRICS:
        for variant_tag, Fam in VARIANTS:
            for quant_tag, Model_tmpl in QUANTS:
                Model = Model_tmpl.format(m=m)
                fn = f"{metric_tag}_{variant_tag}_{quant_tag}.cc"
                path = os.path.join(INST_DIR, fn)
                with open(path, "w") as f:
                    f.write(CC_TEMPLATE.format(
                        ChPoint=ChPoint, m=m, Fam=Fam, Model=Model))
                written_cc.append(fn)

    # Header with extern declarations for all 96 cells.
    decls = []
    for metric_tag, ChPoint, m in METRICS:
        for variant_tag, Fam in VARIANTS:
            for quant_tag, Model_tmpl in QUANTS:
                Model = Model_tmpl.format(m=m)
                for c in ("false", "true "):
                    decls.append(
                        f"extern template void run_one<{ChPoint}, {m}, "
                        f"{Fam}<{m}, {c}, {Model}>>(RunOneCtx<{ChPoint}>&);"
                    )
    with open(HEADER_PATH, "w") as f:
        f.write(HEADER_PRELUDE)
        f.write("\n".join(decls))
        f.write("\n")
        f.write(HEADER_EPILOGUE)

    print(f"Wrote {HEADER_PATH}")
    print(f"Wrote {len(written_cc)} .cc files under {INST_DIR}/")


if __name__ == "__main__":
    main()
