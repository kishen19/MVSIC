#!/usr/bin/env python3
"""Generate bench_search_all_inst.h and the per-cell instantiation .cc files
under bench_search_all_inst/ for the mvivf_spill microbenchmark target.

Run from anywhere:
    python3 microbenchmark/mvivf_spill/gen_bench_search_all_inst.py

Mirrors microbenchmark/mvivf/gen_bench_search_all_inst.py but typed against
IndexMVIVFSpill instead of IndexMVIVF.  The dispatch logic in
bench_search_all.cpp must be updated separately if quantizers are added.
"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
INST_DIR = os.path.join(ROOT, "bench_search_all_inst")
HEADER_PATH = os.path.join(ROOT, "bench_search_all_inst.h")

# (tag, ChPoint type, metric value as C++ literal)
METRICS = [
    ("ip", "ChamferIP_Point", "false"),
    ("l2", "ChamferL2_Point", "true"),
]

# (tag, model template — {m} substitutes the metric literal)
QUANTS = [
    ("none",  "NoQuantizer<{m}>"),
    ("pq",    "pq_mv::Model<{m}>"),
    ("fs",    "fastscan_mv::Model<{m}>"),
    ("rq",    "rabitq_mv::Model<{m}>"),
    ("tq",    "turboquant_mv::Model<{m}>"),
    ("spqtq", "pqtq_mv::Model<{m}>"),
    ("1btq",  "turboquant_1bit_mv::Model<{m}>"),
    ("1btqa", "turboquant_1bit_asym_mv::Model<{m}>"),
]

CC_TEMPLATE = """\
// GENERATED by gen_bench_search_all_inst.py. Do not edit.
#include "microbenchmark/mvivf_spill/bench_search_all_impl.h"

namespace mvsic {{
template void run_one<{ChPoint}, {m}, IndexMVIVFSpill<{m}, false, {Model}>>(
    MicroSpillSearchAllCtx<{ChPoint}>&);
template void run_one<{ChPoint}, {m}, IndexMVIVFSpill<{m}, true,  {Model}>>(
    MicroSpillSearchAllCtx<{ChPoint}>&);
{skeleton}}}  // namespace mvsic
"""

# Skeleton build is only typed against IndexMVIVFSpill<metric, false,
# NoQuantizer>; instantiate it once per metric, in the corresponding
# `*_none.cc` cell.
SKELETON_INST = """\
template void build_skeleton_if_missing<{ChPoint}, {m}>(
    PointCloudSet<{ChPoint}>&, const IndexParams&, const std::string&);
"""

HEADER_PRELUDE = """\
#pragma once
// GENERATED by gen_bench_search_all_inst.py. Do not edit.
//
// Declares run_one<ChPoint, metric, IndexT> and provides extern template
// declarations for every (metric, quantizer, compress) cell of the
// IndexMVIVFSpill microbenchmark so the dispatch TU does not pay to
// instantiate them. Definitions live in bench_search_all_impl.h and are
// explicitly instantiated once per cell under bench_search_all_inst/.

#include <cstddef>
#include <string>
#include <utility>
#include <vector>

#include "parlay/sequence.h"

#include "mvsic/core/index_params.h"
#include "mvsic/core/quantization/fastscan_mv.h"
#include "mvsic/core/quantization/pq_mv.h"
#include "mvsic/core/quantization/pqtq_mv.h"
#include "mvsic/core/quantization/rabitq_mv.h"
#include "mvsic/core/quantization/turboquant_1bit_mv.h"
#include "mvsic/core/quantization/turboquant_1bit_asym_mv.h"
#include "mvsic/core/quantization/turboquant_mv.h"
#include "mvsic/core/types/chamfer_ip_point.h"
#include "mvsic/core/types/chamfer_l2_point.h"
#include "mvsic/core/types/point_cloud_set.h"
#include "mvsic/mvivf/mvivf_spill.h"

namespace mvsic {

template <typename ChPoint>
struct MicroSpillSearchAllCtx {
  PointCloudSet<ChPoint>* points;
  PointCloudSet<ChPoint>* queries;
  IndexParams index_params;
  std::string index_path;
  std::string quant_method_name;
  std::string mode;  // "old" | "new" | "both"
  bool compress_centers;
  std::vector<std::size_t> nprobes_list;
  std::size_t k;
  std::size_t num_rerank;
  parlay::sequence<parlay::sequence<std::pair<uint32_t, float>>> gt;
  bool has_gt;
  // Resolved query-compression options applied to each per-nprobes SearchParams.
  int query_compression;  // SearchParams::QueryCompression as int (avoid header dep here)
  float query_compression_threshold;
  bool compress_rerank;
  bool tq8_rerank;
  bool root_m2m;
};

template <typename ChPoint, bool metric, class IndexT>
void run_one(MicroSpillSearchAllCtx<ChPoint>& ctx);

// Builds and saves the raw NoQuantizer spill skeleton at `index_path` if it
// does not already exist. Typed against
// IndexMVIVFSpill<metric, false, NoQuantizer<metric>>; instantiated once per
// metric in the *_none.cc cells.
template <typename ChPoint, bool metric>
void build_skeleton_if_missing(PointCloudSet<ChPoint>& points,
                               const IndexParams& index_params,
                               const std::string& index_path);

"""

HEADER_EPILOGUE = """\

}  // namespace mvsic
"""


def main():
    os.makedirs(INST_DIR, exist_ok=True)

    written_cc = []
    for metric_tag, ChPoint, m in METRICS:
        for quant_tag, Model_tmpl in QUANTS:
            Model = Model_tmpl.format(m=m)
            skeleton = ""
            if quant_tag == "none":
                skeleton = SKELETON_INST.format(ChPoint=ChPoint, m=m)
            fn = f"{metric_tag}_{quant_tag}.cc"
            path = os.path.join(INST_DIR, fn)
            with open(path, "w") as f:
                f.write(CC_TEMPLATE.format(
                    ChPoint=ChPoint, m=m, Model=Model, skeleton=skeleton))
            written_cc.append(fn)

    decls = []
    for metric_tag, ChPoint, m in METRICS:
        for quant_tag, Model_tmpl in QUANTS:
            Model = Model_tmpl.format(m=m)
            for c in ("false", "true "):
                decls.append(
                    f"extern template void run_one<{ChPoint}, {m}, "
                    f"IndexMVIVFSpill<{m}, {c}, {Model}>>(MicroSpillSearchAllCtx<{ChPoint}>&);"
                )
        decls.append(
            f"extern template void build_skeleton_if_missing<{ChPoint}, {m}>("
            f"PointCloudSet<{ChPoint}>&, const IndexParams&, const std::string&);"
        )

    with open(HEADER_PATH, "w") as f:
        f.write(HEADER_PRELUDE)
        f.write("\n".join(decls))
        f.write("\n")
        f.write(HEADER_EPILOGUE)

    print(f"Wrote {HEADER_PATH}")
    print(f"Wrote {len(written_cc)} .cc files under {INST_DIR}/")


if __name__ == "__main__":
    main()
